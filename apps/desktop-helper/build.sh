#!/bin/sh
# Build and sign the Charon Desktop helper (ai.charon.desktop).
#
# The grants macOS gives this helper are pinned to its signing identity, so
# it must be signed with a stable certificate (a Developer ID), never
# ad hoc: an ad-hoc build loses every grant when it is rebuilt.
#
# The helper only serves a caller whose code satisfies a requirement that
# is generated here and compiled into the signed binary (see
# Sources/Caller.swift). By default that is the exact cdhash of the
# program Charon's venv Python really runs as. After a Python upgrade the
# helper refuses the new interpreter until it is rebuilt: fail closed.
#
#   CHARON_DESKTOP_SIGN_IDENTITY  codesign identity (name or SHA-1); required
#   CHARON_DESKTOP_CALLERS        space-separated caller executables to trust
#                                 (default: what <repo>/.venv/bin/python runs as)
#   CHARON_DESKTOP_OUT            output dir (default: <repo>/build/desktop)
set -eu
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
out=${CHARON_DESKTOP_OUT:-$repo/build/desktop}
identity=${CHARON_DESKTOP_SIGN_IDENTITY:?set CHARON_DESKTOP_SIGN_IDENTITY to a Developer ID codesigning identity}
app="$out/CharonDesktop.app"

if [ -z "${CHARON_DESKTOP_CALLERS:-}" ]; then
    # The image the kernel runs, which can differ from the venv symlink
    # (Homebrew's python re-execs into Python.app).
    CHARON_DESKTOP_CALLERS=$("$repo/.venv/bin/python" -I -c '
import ctypes, os
b = ctypes.create_string_buffer(4096)
ctypes.CDLL("/usr/lib/libproc.dylib").proc_pidpath(os.getpid(), b, 4096)
print(b.value.decode())')
fi

requirement=""
for caller in $CHARON_DESKTOP_CALLERS; do
    cdhash=$(codesign -dvvv "$caller" 2>&1 | sed -n 's/^CDHash=//p')
    [ -n "$cdhash" ] || { echo "cannot read the cdhash of $caller" >&2; exit 1; }
    echo "trusting caller $caller (cdhash $cdhash)"
    clause="cdhash H\\\"$cdhash\\\""
    requirement=${requirement:+$requirement or }$clause
done

gen=$(mktemp -d)
trap 'rm -rf "$gen"' EXIT
cat > "$gen/BuildConfig.swift" <<SWIFT
// Generated by build.sh. Compiled into the signed binary; not configurable.
let allowedCallerRequirement = "$requirement"
SWIFT

rm -rf "$app"
mkdir -p "$app/Contents/MacOS"
cp "$here/Info.plist" "$app/Contents/Info.plist"
swiftc -O -swift-version 5 -o "$app/Contents/MacOS/CharonDesktop" "$here"/Sources/*.swift "$here"/Sources/Kernel/*.swift \
    "$here"/Sources/Capture/*.swift "$here"/Sources/Input/*.swift "$gen/BuildConfig.swift"
# Hardened runtime, no entitlements: the helper needs none of the
# exceptions (no JIT, no unsigned libraries, no debugger attach).
codesign --force --timestamp --options runtime --sign "$identity" "$app"
codesign --verify --strict --verbose=2 "$app"
echo "$app"
